"""References to generative AI output.

Output of a generative AI tool is cited as the tool, not as a published work:
there is nothing to find in Crossref, OpenAlex or on the open web (chat links
are private or need a login), so these references are listed, not checked."""

import re
from urllib.parse import urlparse

GENAI_HOSTS = {
    "chatgpt.com": "ChatGPT", "chat.openai.com": "ChatGPT", "sora.com": "Sora",
    "copilot.microsoft.com": "Microsoft Copilot", "copilot.cloud.microsoft": "Microsoft Copilot",
    "gemini.google.com": "Google Gemini", "bard.google.com": "Google Bard",
    "aistudio.google.com": "Google AI Studio", "notebooklm.google.com": "NotebookLM",
    "claude.ai": "Claude", "perplexity.ai": "Perplexity", "chat.deepseek.com": "DeepSeek",
    "grok.com": "Grok", "meta.ai": "Meta AI", "chat.mistral.ai": "Le Chat (Mistral)",
    "poe.com": "Poe", "character.ai": "Character.AI", "chat.qwen.ai": "Qwen",
    "firefly.adobe.com": "Adobe Firefly", "midjourney.com": "Midjourney",
    "ideogram.ai": "Ideogram", "leonardo.ai": "Leonardo.Ai", "dreamstudio.ai": "DreamStudio",
    "runwayml.com": "Runway", "suno.com": "Suno", "elevenlabs.io": "ElevenLabs",
}
GENAI_NAMES = re.compile(
    r"(?i)\b(chat\s?gpt|gpt-?\d\w*|copilot|gemini|bard|claude|perplexity|deepseek|grok|"
    r"le chat|meta ai|dall[\s·•.\-]*e|midjourney|firefly|stable diffusion|ideogram|"
    r"leonardo\.ai|runway|sora|suno|notebooklm|elevenlabs)\b"
)
GENAI_VENDORS = re.compile(
    r"(?i)^(openai|microsoft|google|anthropic|perplexity|deepseek|xai|x\.ai|meta|mistral|"
    r"adobe|midjourney|stability ai|chatgpt|copilot|gemini|claude)\b"
)
# APA 7 describes the tool in brackets: [Large language model], [Text generated by ChatGPT]
GENAI_LABEL = re.compile(
    r"(?i)\[[^\]]*\b(generative ai|ai[- ]generated|large language model|language model|"
    r"ai chat|chatbot|ai model|text-to-image|generated by)\b[^\]]*\]"
)


def genai_tool(ref, url):
    """-> name of the generative AI tool the reference cites, or None."""
    raw = ref.raw or ""
    host = urlparse(url).netloc.lower().removeprefix("www.") if url else ""
    for h, name in GENAI_HOSTS.items():
        if host == h or host.endswith("." + h):
            return name
    named = GENAI_NAMES.search(raw)
    tool = named.group(0) if named else "unnamed tool"
    if GENAI_LABEL.search(raw):
        return tool
    # "OpenAI. (2024). ChatGPT (May 13 version)." with no label or chat link.
    # Only without a link elsewhere: a vendor's blog post about its tool is a
    # web page and is checked like one.
    if not url and GENAI_VENDORS.match(raw) and named and GENAI_NAMES.search(ref.title or ""):
        return tool
    return None
